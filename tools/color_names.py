#!/usr/bin/env python3
# Writes the named-colour table the eyedropper magnifier names colours from:
#
#   crates/color/src/names_table.rs
#
#   python3 tools/color_names.py ~/.cargo/registry/src/*/color-0.3.3/src/x11_colors.rs crates/color/src/names_table.rs
#
# Source: the CSS Color Module Level 4 named colours (W3C; 148 names with their sRGB values) as listed in the `color`
# crate 0.3.3 (linebender/color, `src/x11_colors.rs`, Apache-2.0 OR MIT). `transparent` is dropped, a name that repeats
# another's value (`aqua`, `fuchsia`) or only spells it differently (`grey`) is dropped, and each name is split into
# words ("cornflowerblue" -> "Cornflower Blue"). Only the Python standard library is used.
import re
import sys
from pathlib import Path

WORDS = """alice antique aquamarine azure beige bisque black blanched almond blue violet brown burlywood cadet
chartreuse chocolate coral cornflower cornsilk crimson cyan dark deep pink sky dim gray dodger firebrick floral white
forest green gainsboro ghost gold goldenrod honeydew hot indian red indigo ivory khaki lavender blush lawn lemon
chiffon light lime linen magenta maroon medium orchid purple turquoise slate spring midnight mint cream misty rose
moccasin navajo navy old lace olive drab orange pale papaya whip peach puff peru plum powder rebecca rosy royal saddle
salmon sandy sea seashell sienna silver snow steel tan teal thistle tomato wheat smoke yellow""".split()
DROPPED = {"transparent", "aqua", "fuchsia", "grey"}


def split(name, words):
    if not name:
        return []
    for w in sorted(words, key=len, reverse=True):
        if name.startswith(w):
            rest = split(name[len(w):], words)
            if rest is not None:
                return [w] + rest
    return None


def main(src, dst):
    text = Path(src).read_text()
    names = re.findall(r'"([a-z]+)"', text.split("pub(crate) const NAMES")[1].split("] = [", 1)[1].split("];")[0])
    colors = re.findall(r"\[(\d+), (\d+), (\d+), \d+\]", text.split("pub(crate) const COLORS")[1].split("] = [", 1)[1].split("];")[0])
    assert len(names) == len(colors), (len(names), len(colors))
    rows = []
    for n, (r, g, b) in zip(names, colors):
        if n in DROPPED or "grey" in n:
            continue
        parts = split(n, WORDS)
        assert parts, n
        rows.append((" ".join(p.capitalize() for p in parts), (int(r), int(g), int(b))))
    rows.sort()
    out = [
        "// Generated by tools/color_names.py from the CSS Color Module Level 4 named colours (see assets/ATTRIBUTION.md).",
        "// Do not hand-edit.",
        "",
        f"pub(crate) const NAMED: [(&str, [u8; 3]); {len(rows)}] = [",
    ]
    out += [f'    ("{n}", [{r}, {g}, {b}]),' for n, (r, g, b) in rows]
    out.append("];")
    Path(dst).write_text("\n".join(out) + "\n")


main(sys.argv[1], sys.argv[2])
